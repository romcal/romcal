import fs from 'node:fs';
import path from 'node:path';

import type { Logger } from '../utils/logger';

/**
 * The fixture of the Easter dates of the `easter` package is generated from the table of
 * `easter-dates.json` (https://github.com/christianpure/bible-data/tree/main/easter-dates, public
 * domain under CC0), which is vendored beside it unchanged. The table gives, for every year from 1900 to
 * 2099, the Easter Sunday of the Western churches (Gregorian computus) and the Pascha of the Orthodox
 * churches (Julian computus), both as civil (Gregorian) dates.
 *
 * Run `romcal-build easter-fixture --input <easter-dates.json> --output <easter-dates.fixture.ts>` to
 * regenerate it. The output is derived from the table and from nothing else, so that the committed
 * fixture can be checked against a fresh generation.
 */

const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;

export interface EasterFixtureDate {
  readonly day: number;
  readonly month: number;
  readonly year: number;
}

export interface EasterFixtureRow {
  readonly julian: EasterFixtureDate;
  readonly gregorian: EasterFixtureDate;
  readonly year: number;
}

const toDate = (value: unknown, label: string): EasterFixtureDate => {
  const match = typeof value === 'string' ? DATE.exec(value) : null;
  if (!match) throw new Error(`${label}: "${String(value)}" is not a date written YYYY-MM-DD.`);
  return { day: Number(match[3]), month: Number(match[2]), year: Number(match[1]) };
};

/**
 * Read the rows of the table: the year, the Western Easter and the Orthodox Easter of each.
 *
 * @param text The content of `easter-dates.json`.
 * @throws If the table has no rows, if a row misses a field, or if a date is malformed, or if the year of a
 * date is not the year of its row.
 */
export const readEasterRows = (text: string): EasterFixtureRow[] => {
  const table = JSON.parse(text) as { years?: Record<string, unknown>[] };
  if (!Array.isArray(table.years) || table.years.length === 0) {
    throw new Error('The table has no "years" to read.');
  }

  return table.years.map((row) => {
    const year = row.year;
    if (!Number.isInteger(year)) throw new Error(`"${String(year)}" is not a year.`);

    const gregorian = toDate(row.western_easter, `western_easter of ${String(year)}`);
    const julian = toDate(row.orthodox_easter, `orthodox_easter of ${String(year)}`);
    if (gregorian.year !== year || julian.year !== year) {
      throw new Error(`An Easter date of ${String(year)} falls in another year.`);
    }
    return { gregorian, julian, year: year as number };
  });
};

const renderRecord = (name: string, doc: string, dates: readonly EasterFixtureDate[]): string =>
  [
    '/**',
    ` * ${doc}`,
    ' */',
    `export const ${name}: Record<string, EasterDate> = {`,
    ...dates.map(({ day, month, year }) => `  '${year}': { year: ${year}, month: ${month}, day: ${day} },`),
    '};',
  ].join('\n');

/**
 * Render the TypeScript module of the fixture.
 *
 * @param rows The rows read from the table, one per year.
 */
export const renderEasterFixture = (rows: readonly EasterFixtureRow[]): string =>
  [
    "import { EasterDate } from '..';",
    '',
    '// Generated by `romcal-build easter-fixture` from `easter-dates.json`. Do not edit: change the table or the',
    '// command, and generate it again.',
    '',
    renderRecord(
      'gregorianEasterDatesFixture',
      'Gregorian Easter Sunday, by year.',
      rows.map((row) => row.gregorian)
    ),
    '',
    renderRecord(
      'julianEasterDatesFixture',
      'Julian Easter Sunday, expressed in the Gregorian calendar, by year.',
      rows.map((row) => row.julian)
    ),
    '',
  ].join('\n');

/**
 * Generate the fixture from the table.
 *
 * @param flags The flags of the command: `input` is the path of `easter-dates.json`, `output` the path of the
 * fixture to write.
 * @param log The logger of the build.
 * @throws If `input` or `output` is missing.
 */
export const runEasterFixture = (flags: Readonly<Record<string, string | boolean>>, log: Logger): void => {
  const { input, output } = flags;
  if (typeof input !== 'string' || typeof output !== 'string') {
    throw new Error('easter-fixture needs --input <easter-dates.json> and --output <easter-dates.fixture.ts>.');
  }

  const rows = readEasterRows(fs.readFileSync(input, 'utf8'));
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, renderEasterFixture(rows));
  log.success(`${rows.length} years written to ${output}.`);
};
