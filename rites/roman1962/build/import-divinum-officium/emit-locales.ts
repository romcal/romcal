import fs from 'node:fs';
import path from 'node:path';

import { STRUCTURE, type LocaleStructure } from './locale-structure';
import type { MassEntry } from './types';

type Source = 'sancti' | 'tempora' | 'commune';

function pivotNames(
  groups: { source: Source; entries: Record<string, MassEntry> }[]
): Record<string, Record<string, string>> {
  const out: Record<string, Record<string, string>> = {};
  for (const { source, entries } of groups) {
    for (const [key, entry] of Object.entries(entries)) {
      const id = `${source}/${key}`;
      // Latin authoritative name lives on `officium` (the [Officium] block of
      // the .txt), not on `names` (which holds vernaculars). Surface it under
      // 'la' so consumers that request Latin get a consistent lookup.
      if (entry.officium) (out.la ??= {})[id] = entry.officium;
      const names = entry.names ?? {};
      for (const [lang, name] of Object.entries(names)) {
        if (!name) continue;
        (out[lang] ??= {})[id] = name;
      }
    }
  }
  return out;
}

function serialize(value: unknown, indent = 2, depth = 1): string {
  const pad = ' '.repeat(indent * depth);
  const close = ' '.repeat(indent * (depth - 1));
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map((v) => `${pad}${serialize(v, indent, depth + 1)}`).join(',\n');
    return `[\n${items}\n${close}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  if (entries.length === 0) return '{}';
  const lines = entries.map(([k, v]) => `${pad}${JSON.stringify(k)}: ${serialize(v, indent, depth + 1)}`).join(',\n');
  return `{\n${lines}\n${close}}`;
}

function renderLocaleFile(langId: string, names: Record<string, string>, structure?: LocaleStructure): string {
  const sortedNames = Object.fromEntries(Object.entries(names).sort(([a], [b]) => a.localeCompare(b)));
  const lines = [
    `// AUTO-GENERATED by build/import-divinum-officium/emit-locales.ts — do not edit by hand.`,
    `// Regenerate with: npm run import:do -w @internal/rite-roman1962`,
    `import type { Locale1962 } from '../types/locale';`,
    ``,
    `export const locale: Locale1962 = {`,
    `  id: ${JSON.stringify(langId)},`,
  ];
  if (structure?.colors) lines.push(`  colors: ${serialize(structure.colors, 2, 2)},`);
  if (structure?.ranks) lines.push(`  ranks: ${serialize(structure.ranks, 2, 2)},`);
  if (structure?.seasons) lines.push(`  seasons: ${serialize(structure.seasons, 2, 2)},`);
  if (structure?.months) lines.push(`  months: ${serialize(structure.months, 2, 2)},`);
  if (structure?.weekdays) lines.push(`  weekdays: ${serialize(structure.weekdays, 2, 2)},`);
  lines.push(`  names: ${serialize(sortedNames, 2, 2)},`);
  lines.push(`};`);
  lines.push(``);
  return lines.join('\n');
}

function bcpToVarName(lang: string): string {
  return lang
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

function renderIndexFile(langs: string[]): string {
  const sorted = [...langs].sort();
  const imports = sorted.map((l) => `import { locale as ${bcpToVarName(l)} } from './${l}';`).join('\n');
  const entries = sorted.map((l) => `  ${JSON.stringify(l)}: ${bcpToVarName(l)},`).join('\n');
  return [
    `// AUTO-GENERATED by build/import-divinum-officium/emit-locales.ts — do not edit by hand.`,
    `import type { Locale1962 } from '../types/locale';`,
    ``,
    imports,
    ``,
    `export const locales: Record<string, Locale1962> = {`,
    entries,
    `};`,
    ``,
    `export const localeIds = Object.keys(locales);`,
    ``,
  ].join('\n');
}

/**
 * Pivot per-entry `names[lang]` from the three mass sources into one
 * `rites/roman1962/src/locales/{lang}.ts` file per locale. Also emit a
 * `locales/index.ts` aggregator. Structural labels (colors, ranks, seasons,
 * months, weekdays) come from the static STRUCTURE table — langs without a
 * STRUCTURE entry get names-only and fall back to English at bundle time.
 */
export function emitLocales(
  tempora: Record<string, MassEntry>,
  sancti: Record<string, MassEntry>,
  commune: Record<string, MassEntry>,
  supportedLocales: string[],
  outDir: string
): { locales: number; total: number } {
  fs.mkdirSync(outDir, { recursive: true });

  const pivoted = pivotNames([
    { source: 'sancti', entries: sancti },
    { source: 'tempora', entries: tempora },
    { source: 'commune', entries: commune },
  ]);

  const emitted: string[] = [];
  let total = 0;
  for (const lang of supportedLocales) {
    const names = pivoted[lang] ?? {};
    const structure = STRUCTURE[lang];
    // Skip locales with no names AND no structure — avoid emitting empty files.
    if (Object.keys(names).length === 0 && !structure) continue;
    const file = path.join(outDir, `${lang}.ts`);
    fs.writeFileSync(file, renderLocaleFile(lang, names, structure), 'utf8');
    emitted.push(lang);
    total += Object.keys(names).length;
  }

  // Always include 'la' in the aggregator so callers can request Latin.
  if (!emitted.includes('la')) {
    const laStructure = STRUCTURE.la;
    if (laStructure) {
      fs.writeFileSync(path.join(outDir, 'la.ts'), renderLocaleFile('la', {}, laStructure), 'utf8');
      emitted.push('la');
    }
  }

  fs.writeFileSync(path.join(outDir, 'index.ts'), renderIndexFile(emitted), 'utf8');

  return { locales: emitted.length, total };
}
