/**
 * Emit per-locale self-contained bundles under `dist/bundles/`.
 *
 * Each bundle ships one locale's `Locale1962` (merged En→la so fallbacks are
 * baked in) plus every per-section proper-text map for the three sources
 * (sancti/tempora/commune). Consumers that import a bundle never need i18next
 * nor the per-locale JSON files in `data/propers/{lang}/`.
 *
 * Output per locale `{lang}`:
 *   dist/bundles/{lang}.js   (esbuild-bundled, esm)
 *   dist/bundles/{lang}.cjs  (esbuild-bundled, cjs)
 *   dist/bundles/{lang}.d.ts
 */
import fs from 'node:fs';
import path from 'node:path';

import chalk from 'chalk';
import { build } from 'esbuild';
import { rimraf } from 'rimraf';
import { merge } from 'ts-deepmerge';

import { locales } from '../src/locales';
import type { Locale1962 } from '../src/types/locale';

const { log } = console;

type Source = 'sancti' | 'tempora' | 'commune';
const SOURCES: Source[] = ['sancti', 'tempora', 'commune'];
type PropersText = Record<string, Record<string, string[]>>;
type BundlePropers = Record<Source, PropersText>;

const DATA_DIR = path.resolve(__dirname, '../data');
const PROPERS_DIR = path.join(DATA_DIR, 'propers');
const OUT_DIR = path.resolve(__dirname, '../dist/bundles');
const TMP_DIR = path.resolve(__dirname, '../tmp/bundles');

function loadPropers(lang: string): BundlePropers {
  const out = { sancti: {}, tempora: {}, commune: {} } as BundlePropers;
  for (const source of SOURCES) {
    const file = path.join(PROPERS_DIR, lang, `${source}.json`);
    if (fs.existsSync(file)) {
      out[source] = JSON.parse(fs.readFileSync(file, 'utf8')) as PropersText;
    }
  }
  return out;
}

function emitSource(lang: string, i18n: Locale1962, propers: BundlePropers): string {
  const bundle = { id: lang, i18n, propers };
  return [
    '/* AUTO-GENERATED by build/bundle.ts — do not edit by hand. */',
    "import type { RomcalBundle1962 } from '../../src/bundles/types';",
    '',
    `export const bundle: RomcalBundle1962 = ${JSON.stringify(bundle)};`,
    'export default bundle;',
    '',
  ].join('\n');
}

async function run(): Promise<void> {
  log(chalk.bold(`\n  –– ${chalk.red('Romcal 1962')} bundler ––`));

  rimraf.sync(OUT_DIR);
  rimraf.sync(TMP_DIR);
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.mkdirSync(TMP_DIR, { recursive: true });

  const en = locales.en;
  const la = locales.la;
  const ids = Object.keys(locales);

  log(chalk.bold(`\n✓ Writing ${ids.length} locale bundles → ${chalk.cyan('./dist/bundles/')}`));

  for (const lang of ids) {
    const mergedI18n = (lang === 'la' ? la : merge(la, en, locales[lang])) as Locale1962;
    mergedI18n.id = lang;
    const propers = loadPropers(lang);
    const tsSource = emitSource(lang, mergedI18n, propers);
    const tsPath = path.join(TMP_DIR, `${lang}.ts`);
    fs.writeFileSync(tsPath, tsSource, 'utf8');

    for (const format of ['esm', 'cjs'] as const) {
      await build({
        bundle: true,
        minify: true,
        sourcemap: 'external',
        entryPoints: [tsPath],
        format,
        outfile: path.join(OUT_DIR, `${lang}.${format === 'esm' ? 'js' : 'cjs'}`),
        target: format === 'esm' ? 'ESNext' : 'ES2022',
        platform: 'node',
      });
    }

    const dts = [
      "import type { RomcalBundle1962 } from '../../dist/index';",
      '',
      'export declare const bundle: RomcalBundle1962;',
      'export default bundle;',
      '',
    ].join('\n');
    fs.writeFileSync(path.join(OUT_DIR, `${lang}.d.ts`), dts, 'utf8');

    log(chalk.dim(`  • ${lang}`));
  }

  log(chalk.green('\n✨ Done'));
}

run().catch((err) => {
  log(chalk.red(String(err)));
  process.exit(1);
});
