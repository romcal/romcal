import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import type { Logger } from '../utils/logger';

import { readEasterRows, renderEasterFixture, runEasterFixture } from './easter-fixture';

const EASTER_DIR = path.resolve(__dirname, '../../../easter/src/fixtures');

const table = (rows: Record<string, unknown>[]): string => JSON.stringify({ years: rows });
const row = (year: number, western: string, orthodox: string): Record<string, unknown> => ({
  orthodox_easter: orthodox,
  western_easter: western,
  year,
});

describe('readEasterRows', () => {
  it('reads the Western and the Orthodox Easter of every year', () => {
    expect(readEasterRows(table([row(2025, '2025-04-20', '2025-04-20'), row(2026, '2026-04-05', '2026-04-12')]))).toEqual(
      [
        { gregorian: { day: 20, month: 4, year: 2025 }, julian: { day: 20, month: 4, year: 2025 }, year: 2025 },
        { gregorian: { day: 5, month: 4, year: 2026 }, julian: { day: 12, month: 4, year: 2026 }, year: 2026 },
      ]
    );
  });

  it.each([['{}'], ['{"years":[]}'], ['{"years":"2025"}']])('refuses a table without rows (%s)', (text) => {
    expect(() => readEasterRows(text)).toThrow('The table has no "years" to read.');
  });

  it('refuses a year that is not an integer', () => {
    expect(() => readEasterRows(table([row(2025.5, '2025-04-20', '2025-04-20')]))).toThrow('"2025.5" is not a year.');
  });

  it.each([
    ['2025-4-20', 'western_easter of 2025'],
    ['20 April 2025', 'western_easter of 2025'],
  ])('refuses a Western date written "%s"', (value, label) => {
    expect(() => readEasterRows(table([row(2025, value, '2025-04-20')]))).toThrow(
      `${label}: "${value}" is not a date written YYYY-MM-DD.`
    );
  });

  it('refuses an Orthodox date that is missing', () => {
    expect(() => readEasterRows(table([{ western_easter: '2025-04-20', year: 2025 }]))).toThrow(
      'orthodox_easter of 2025: "undefined" is not a date written YYYY-MM-DD.'
    );
  });

  it.each([
    ['Western', row(2025, '2026-04-05', '2025-04-20')],
    ['Orthodox', row(2025, '2025-04-20', '2024-05-05')],
  ])('refuses a %s date that falls in another year', (_name, bad) => {
    expect(() => readEasterRows(table([bad]))).toThrow('An Easter date of 2025 falls in another year.');
  });
});

describe('renderEasterFixture', () => {
  const rows = readEasterRows(table([row(2026, '2026-04-05', '2026-04-12')]));

  it('renders the two records, keyed by year', () => {
    const text = renderEasterFixture(rows);

    expect(text).toContain("export const gregorianEasterDatesFixture: Record<string, EasterDate> = {\n  '2026': { year: 2026, month: 4, day: 5 },\n};");
    expect(text).toContain("export const julianEasterDatesFixture: Record<string, EasterDate> = {\n  '2026': { year: 2026, month: 4, day: 12 },\n};");
  });

  it('says that the module is generated', () => {
    expect(renderEasterFixture(rows)).toContain('// Generated by `romcal-build easter-fixture`');
  });
});

describe('the committed fixture of the easter package', () => {
  const vendored = readEasterRows(fs.readFileSync(path.join(EASTER_DIR, 'easter-dates.json'), 'utf8'));

  it('covers 200 years', () => {
    expect(vendored).toHaveLength(200);
  });

  it('is what the command generates from the vendored table, so that a fresh generation gives no diff', () => {
    expect(fs.readFileSync(path.join(EASTER_DIR, 'easter-dates.fixture.ts'), 'utf8')).toBe(renderEasterFixture(vendored));
  });
});

describe('runEasterFixture', () => {
  let dir: string;
  const log = { success: jest.fn() } as unknown as Logger;

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'easter-fixture-'));
    jest.clearAllMocks();
  });
  afterEach(() => fs.rmSync(dir, { force: true, recursive: true }));

  it('writes the fixture, creating the folder of the output', () => {
    const input = path.join(dir, 'easter-dates.json');
    const output = path.join(dir, 'nested', 'easter-dates.fixture.ts');
    fs.writeFileSync(input, table([row(2026, '2026-04-05', '2026-04-12')]));

    runEasterFixture({ input, output }, log);

    expect(fs.readFileSync(output, 'utf8')).toBe(renderEasterFixture(readEasterRows(fs.readFileSync(input, 'utf8'))));
    expect(log.success).toHaveBeenCalledWith(`1 years written to ${output}.`);
  });

  it.each([[{}], [{ input: 'a.json' }], [{ output: 'a.ts' }], [{ input: true, output: 'a.ts' }]])(
    'refuses flags that miss --input or --output (%j)',
    (flags) => {
      expect(() => runEasterFixture(flags, log)).toThrow('easter-fixture needs --input');
    }
  );
});
